export const r7FebBills: Tagged[] = [];
export const r7FebContents: Content[] = [];

function add(s: Spec) {
  r7FebBills.push({
    originating_house: "HR",
    status: "enacted",
    status_note: s.note,
    submitted_date: `${s.submitted}T10:00:00+09:00`,
    publish_status: "published",
    published_at: "2026-10-22T09:00:00+09:00",
    shugiin_url: KAIGIROKU_URL,
    name: s.name,
    tag: s.tag,
    ...(s.featured ? { is_featured: true } : {}),
  });
  const qaN = s.qa?.length
    ? `\n## 委員会で出た主な質問\n\n${s.qa.map(([q, a]) => `- **${q}** → ${a}、との答弁`).join("\n")}\n`
    : "";
  const qaH = s.qa?.length
    ? `\n## 委員会での主な質疑\n\n| 論点 | 答弁の要旨 |\n|---|---|\n${s.qa.map(([q, a]) => `| ${q.replace(/[？?]$/, "")} | ${a} |`).join("\n")}\n`
    : "";
  r7FebContents.push(
    {
      bill_name: s.name,
      difficulty_level: "normal",
      title: s.title,
      summary: s.summary,
      content: `# ${s.title}

${s.normal}
${qaN}
## 結果

- ${s.committee}
- ${s.plenary}

${SOURCE_NOTE}`,
    },
    {
      bill_name: s.name,
      difficulty_level: "hard",
      title: s.hardTitle,
      summary: s.hardSummary,
      content: `# ${s.hardTitle}

${s.hard}
${qaH}
## 審査結果

- ${s.committeeHard}
- ${s.plenaryHard}

${SOURCE_NOTE}`,
    }
  );
}

